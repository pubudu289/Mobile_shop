private void LoadingProgressbar() {
        Thread t = new Thread(new Runnable() {
            @Override
            public void run() {
                try {
                    for (int i = 0; i < 101; i++) {
                        jProgressBar1.setValue(i);
                        lbl_pcount.setText(i + "%");
                        if (i == 5) {
                            lbl_detail.setText("Database Cheking...");
                            Connection newConnection = DB.getNewConnection();
                            if (newConnection == null) {
                                break;
                            }
                        }
                        if (i >= 50 && i <= 70) {
                            lbl_detail.setText("Database Connected");
                            Thread.sleep(50);
                            continue;
                        }
                        if (i >= 70 && i <= 90) {
                            lbl_detail.setText("Continue...");
                            Thread.sleep(20);
                            continue;
                        }
                        if (i == 100) {
                            Home h = new Home();
                            h.setVisible(true);
                            dispose();
                        }
                        Thread.sleep(20);
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        });
        t.start();
    }


