    private void btn_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_loginActionPerformed
         try {
            String username = txt_username.getText();
            String password = new String(txt_pass.getPassword());
            String MD5 = Encription.getMd5(password);
            String sql = "select * from login where username = ? and password = ?";
             Connection con = DB.getNewConnection();
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, username);
            ps.setString(2, MD5);
            ResultSet search = ps.executeQuery();
            if (search.next()) {
                    boolean isactive = search.getBoolean("isactive");
                    if (isactive) {
                        
                        SystemData.setCurrentUser(username);
                        SystemData.setUserId(search.getString("id"));
                        
                        lbl_logs.setText(null);
                        lbl_success.setText("Login Successful..");
                        jProgressBar1.setVisible(true);
                        LoadingProgressbar();
                    } else {
                        lbl_logs.setText("This User Inactive..");
                        clearFields();
                    }
            } else {
                lbl_logs.setText("Invalid User Name or Password..");
                clearFields();
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
                           
    }//GEN-LAST:event_btn_loginActionPerformed

