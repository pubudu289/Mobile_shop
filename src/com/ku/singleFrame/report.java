    private void loadTable() {
        try {
            ResultSet rs = DB.search("SELECT mobile_details.mob_id,mobile_details.mob_name,mobile_details.mob_power_status,"
                    + "mobile_details.mob_date,mobile_status.description,mobile_details.mob_submit_date"
                    + " FROM mobile_details INNER JOIN mobile_status "
                    + "ON mobile_details.mob_status = mobile_status.id where mobile_status.isactive ='1'");
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("mob_id"));
                v.add(rs.getString("mob_name"));
                v.add(rs.getString("mob_power_status"));
                v.add(rs.getString("mob_date"));
                v.add(rs.getString("mob_submit_date"));
                v.add(rs.getString("mobile_status.description"));
                dtm.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }

    private void orderCount() {
        try {
            String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            ResultSet rs = DB.search("select count(mob_id) as x from mobile_details where mob_date = '" + date + "'");
            if (rs.next()) {
                lbl_today_work.setText(rs.getString("x"));
            }

            String month = new SimpleDateFormat("yyyy-MM").format(new Date());
            ResultSet rs1 = DB.search("select count(mob_id) as y from mobile_details where mob_date like'" + month + "%'");
            if (rs1.next()) {
                lbl_monthly_work.setText(rs1.getString("y"));
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadCombo() {
        try {
            ResultSet rs = DB.search("select * from mobile_status");
            Vector v = new Vector();
            while (rs.next()) {
                String record = rs.getString("description");
                v.add(record);
            }
            Combo_status.setModel(new DefaultComboBoxModel<>(v));
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void clearAll() {

        Combo_status.setSelectedIndex(0);
        ta_description.setText(null);
        lbl_pen_count.setText("0");
        lbl_sus_count.setText("0");
        lbl_reje_count.setText("0");
        dc_day.setDate(null);
        dc_end.setDate(null);
        dc_start.setDate(null);
        loadTable();
        loadCart();
    }

