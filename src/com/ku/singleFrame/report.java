    private void Combo_statusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Combo_statusActionPerformed
        try {
            int stat = Combo_status.getSelectedIndex();

            ResultSet rs = DB.search("SELECT mobile_details.mob_id,mobile_details.mob_name,mobile_details.mob_power_status,"
                    + "mobile_details.mob_date,mobile_status.description,mobile_details.mob_submit_date,mobile_details.isactive"
                    + " FROM mobile_details INNER JOIN mobile_status "
                    + "ON mobile_details.mob_status = mobile_status.id where mob_status='" + stat + "' and mobile_details.isactive = '1'");

            int status = Combo_status.getSelectedIndex();
            switch (status) {
                case 0:
                    ResultSet rs1 = DB.search("select count(mob_id)as x from mobile_details where mob_status = '" + status + "' and isactive = '1' ");
                    if (rs1.next()) {
                        lbl_pen_count.setText(rs1.getString("x"));
                        lbl_reje_count.setText("0");
                        lbl_sus_count.setText("0");
                    }
                    break;

                case 1:
                    ResultSet rs2 = DB.search("select count(mob_id)as y from mobile_details where mob_status = '" + status + "' and isactive = '1' ");
                    if (rs2.next()) {
                        lbl_sus_count.setText(rs2.getString("y"));
                        lbl_reje_count.setText("0");
                        lbl_pen_count.setText("0");
                    }
                    break;
                case 2:
                    ResultSet rs3 = DB.search("select count(mob_id)as z from mobile_details where mob_status = '" + status + "' and isactive = '1'");
                    if (rs3.next()) {
                        lbl_reje_count.setText(rs3.getString("z"));
                          lbl_pen_count.setText("0");
                          lbl_sus_count.setText("0");
                    }
                    break;
            }

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);
            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("mob_id"));
                v.add(rs.getString("mob_name"));
                v.add(rs.getString("mob_power_status"));
                v.add(rs.getString("mob_date"));
                v.add(rs.getString("mob_submit_date"));
                v.add(rs.getString("mobile_status.description"));
                dtm.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_Combo_statusActionPerformed

