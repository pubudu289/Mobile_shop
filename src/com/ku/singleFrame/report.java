    private void loadCart() {
        try {
            
            int pending = 0;
            ResultSet rs2 = DB.search("select count(mob_id) as z from mobile_details where mob_status = '" + pending + "'");
            if (rs2.next()) {
                lbl_pending_all.setText(rs2.getString("z"));
            }

            int success = 1;
            ResultSet rs3 = DB.search("select count(mob_id) as a from mobile_details where mob_status = '" + success + "'");
            if (rs3.next()) {
                lbl_success_all.setText(rs3.getString("a"));
            }

            int reject = 2;
            ResultSet rs4 = DB.search("select count(mob_id) as b from mobile_details where mob_status = '" + reject + "'");
            if (rs4.next()) {
                lbl_reject_all.setText(rs4.getString("b"));
            }

            ResultSet rs5 = DB.search("select count(mob_id) as c from mobile_details");
            if (rs5.next()) {
                lbl_all_works.setText(rs5.getString("c"));
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
